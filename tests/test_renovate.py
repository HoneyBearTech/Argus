"""Regressions for automated updates of pip-compile outputs."""

from __future__ import annotations

import json
import re
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent


def test_compiled_requirements_have_a_hash_regenerating_manager() -> None:
    config = json.loads((ROOT / "renovate.json").read_text())
    patterns = config.get("pip-compile", {}).get("managerFilePatterns", [])
    compiled = [path for path in ROOT.glob("requirements*.txt") if "autogenerated by pip-compile" in path.read_text()]
    assert compiled
    for path in compiled:
        assert any(re.search(pattern[1:-1], path.name) for pattern in patterns), path.name
        header = path.read_text().split("\n\n", maxsplit=1)[0]
        assert "--generate-hashes" in header
        sources = re.findall(r"\b[\w.-]+\.in\b", header)
        assert sources
        assert all((ROOT / source).is_file() for source in sources)
    # The pip-compile manager parses its sources itself. A second manager can
    # update the compiled output independently of the source and its hashes.
    assert config["pip_requirements"]["enabled"] is False
